#define ZERO_TABLE_LEN  (int)(sizeof(zero_table)/sizeof(zero_table[0]))
#define WIDE_TABLE_LEN  (int)(sizeof(wide_table)/sizeof(wide_table[0]))

/*
 * bisect: binary search -- returns 1 if cp falls in [start,end] of
 * any table entry, 0 otherwise.
 */
static int
bisect(unsigned int cp, const struct wchar_tab *tab, int n)
{
    int lo = 0, hi = n - 1;
    while (lo <= hi) {
        int mid = (lo + hi) / 2;
        if (cp > tab[mid].end)
            lo = mid + 1;
        else if (cp < tab[mid].start)
            hi = mid - 1;
        else
            return 1;
    }
    return 0;
}

/*
 * ucswidth: return display width of a Unicode codepoint.
 *   -1 for non-printable (control chars), 0 for combining/zero-width,
 *    1 for narrow, 2 for wide.
 */
int
ucswidth(unsigned int cp)
{
    /* C0 controls and DEL; C1 controls */
    if (cp < 32 || (cp >= 0x7F && cp < 0xA0))
        return -1;

    /* Zero-width / combining characters */
    if (bisect(cp, zero_table, ZERO_TABLE_LEN))
        return 0;

    /* Wide / fullwidth characters */
    if (bisect(cp, wide_table, WIDE_TABLE_LEN))
        return 2;

    /* Default: narrow */
    return 1;
}

/*
 * char_width: return the terminal display width of a kemacs internal
 * Char value.
 *
 * kemacs stores characters in several internal representations:
 *   0x0000-0x007F   : ASCII (direct Unicode codepoint)
 *   0x0100-0x017F   : Half-width katakana (enkana encoded; narrow)
 *   0x2121-0x7E7E   : JIS X 0208 (EUC-JP byte-pair, 0x80 stripped)
 *   0x10000+        : Unicode codepoint >= 0x10000 (stored directly)
 *   0x200000 | cp   : BMP Unicode codepoint (< 0x10000) tagged with
 *                     UNICODE_MARK, because it has no EUC-JP equivalent
 *
 * Returns:
 *   0 -- zero-width (combining marks, ZWJ, variation selectors)
 *   1 -- narrow (1 column)
 *   2 -- wide (2 columns)
 */
int
char_width(unsigned int c)
{
    unsigned int uc;

    /* ASCII: always 1 column (control chars handled separately by caller) */
    if (c < 0x80)
        return 1;

    /* Half-width katakana: always narrow (1 column) */
    if (c >= 0x0100 && c <= 0x017F)
        return 1;

    /* JIS X 0208 kanji: use existing narrow-kanji logic */
    if (iskanji(c))
        return is_narrow_kanji(c) ? 1 : 2;

    /* Unicode codepoints (>= 0x10000, or tagged BMP with UNICODE_MARK) */
    if (isunicode(c)) {
        uc = (unsigned int)UNICODE_CP(c);   /* strip UNICODE_MARK if present */
        int w = ucswidth(uc);
        if (w < 0) return 1;                /* invalid: fallback to 1 */
        return w;                            /* 0, 1, or 2 */
    }

    /* 8-bit characters (0x80-0xFF): shouldn't occur in normal operation */
    return 1;
}
