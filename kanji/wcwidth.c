/*
 * wcwidth.c -- Unicode East Asian Width implementation for kemacs
 *
 * Based on Markus Kuhn's wcwidth.c (public domain).
 * Implements Unicode Standard Annex #11 (East Asian Width) for
 * proper display width calculation of wide characters, combining
 * characters, and zero-width characters.
 *
 * Provides:
 *   ucswidth(cp)   -- width of a Unicode codepoint (0, 1, or 2; -1 if invalid)
 *   char_width(c)  -- width of a kemacs internal Char (0, 1, or 2)
 *
 * The iswidechar() and iscombchar() macros in kanji.h now delegate
 * to char_width() instead of the old heuristic that treated ALL
 * codepoints >= 0x10000 as 2-column wide.
 *
 * NOTE: iscombchar() is defined as a macro in kanji.h:
 *       #define iscombchar(c) (char_width(c) == 0)
 * Do NOT define it as a function here to avoid macro conflicts.
 */

#include "kanji.h"
#include "wcwidth.h"

